def build():
    OUT.mkdir(parents=True,exist_ok=True)
    manifest=json.loads((R/'ti84/manifest.json').read_text())
    required={p['name'] for p in manifest['programs'] if p['name']!='BME423'}
    assert len(GUIDES)==len(required)==len({g['name'] for g in GUIDES})==36
    assert {g['name'] for g in GUIDES}==required
    # Page labels use AA..ZY, with ZZ reserved for EXIT. Menus use M + digit/A.
    labels=iter(a+b for a,b in itertools.product(string.ascii_uppercase,repeat=2) if a+b not in {'MA','ZZ'})
    pages=[]
    def page(header,title,body,method=None):
        wrapped=[line for row in body for line in textwrap.wrap(native(row),26,break_long_words=False,break_on_hyphens=False)]
        result=[]
        for i in range(0,len(wrapped),7):
            label=next(labels)
            caption=title if i==0 else title[:20]+' CONT.'
            rows=[native(row) for row in [header,caption,*wrapped[i:i+7]]]
            assert len(rows)<=9,(header,title,len(rows))
            for row in rows:assert len(row)<=26 and '"' not in row,(header,row,len(row))
            p=dict(label=label,rows=rows,method=method,step=title)
            pages.append(p);result.append(p)
        return result
    intro=page('BMSTEPS','READ, THEN FILL IN',[
        'CHOOSE THE QUESTION TYPE.','COPY YOUR NUMBERS ON PAPER.','FOLLOW EACH FORMULA.','ENTER=NEXT; LEFT=BACK.','CLEAR=MAIN MENU.','EXISTING BME423 DOES MATH.'])[0]
    notation=page('QUICK SYMBOL KEY','MATH ON THE CE SCREEN',[
        'SQRT(X)=SQUARE ROOT.','X^2=X SQUARED.','ABS(X)=MAGNITUDE, NO SIGN.','SUM=ADD ALL THOSE TERMS.','____=YOUR NUMBER OR RESULT.','MU=POPULATION MEAN.'])[0]
    intro['next']=notation['label'];intro['prev']=intro['label']
    notation['next']='M0';notation['prev']=intro['label']
    for g in GUIDES:
        group=[]
        group.extend(page(g['title'],'WHEN / WHAT TO COPY',g['recognize'],g['name']))
        for title,body in g['steps']:group.extend(page(g['title'],title,body,g['name']))
        group.extend(page(g['title'],'WRITE THE ANSWER',g['answer'],g['name']))
        g['label']=group[0]['label'];g['pages']=[p['label'] for p in group]
        for i,p in enumerate(group):
            p['prev']=group[max(0,i-1)]['label']
            p['next']=group[i+1]['label'] if i+1<len(group) else 'M0'
    names={g['name']:g['label'] for g in GUIDES}
    # One shared viewer keeps the entire guide within one TI program variable.
    # P=current page, B=first page, C=last page; T (a saved PDF endpoint) is kept.
    for i,p in enumerate(pages,1):p['index']=i
    numbers={p['label']:p['index'] for p in pages}
    lines=['ClrHome','1→P','1→B','2→C','Goto D0']
    for label,(title,items) in MENUS.items():
        assert len(items)<=7
        args=[f'"{title}"']
        for caption,dest in items:
            assert len(caption)<=26
            args.extend([f'"{caption}"',names.get(dest,dest)])
        lines += ['Lbl '+label,'Menu('+','.join(args)+')']
    for g in GUIDES:
        first=numbers[g['pages'][0]];last=numbers[g['pages'][-1]]
        lines += ['Lbl '+g['label'],f'{first}→P',f'{first}→B',f'{last}→C','Goto D0']
    lines += ['Lbl D0','ClrHome']
    for p in pages:
        lines += [f'If P={p["index"]}','Then']
        for row,text in enumerate(p['rows'],1):lines.append(f'Output({row},1,"{text}")')
        lines.append('End')
        footer='ENTER> LEFT:BACK CLR:MENU' if p['next']!='M0' else 'ENTER:MENU LEFT:BACK CLR'
        assert len(footer)<=26
        p['rows']=(p['rows']+['']*(9-len(p['rows']))+[footer])
    lines += ['If P=C','Then','Output(10,1,"ENTER:MENU LEFT:BACK CLR")','Else',
              'Output(10,1,"ENTER> LEFT:BACK CLR:MENU")','End','0→θ',
              'Repeat θ=105 or θ=26 or θ=24 or θ=45','getKey→θ','End',
              'If θ=45','Goto M0','If θ=24','max(B,P-1)→P','If θ=24','Goto D0',
              'If P=C','Goto M0','P+1→P','Goto D0']
    lines += ['Lbl ZZ','ClrHome','Stop']
    source='\n'.join(lines)+'\n'
    labels_in=re.findall(r'^Lbl (\w+)$',source,re.M)
    assert len(labels_in)==len(set(labels_in))
    with warnings.catch_warnings():
        warnings.simplefilter('error')
        program=TIProgram(name='BMSTEPS');program.load_string(source,model=TI_84PCEPY)
        assert len(program.data)<65512,('TI program size limit',len(program.data))
        program.save(str(OUT/'BMSTEPS.8xp'),model=TI_84PCEPY)
        a=TIProgram.open(str(OUT/'BMSTEPS.8xp'))
        assert a.data==program.data and a.supported_by(TI_84PCEPY)
    (OUT/'BMSTEPS.txt').write_text(source)
    lookup={label:dict(title=title,items=[dict(title=t,destination=names.get(d,d)) for t,d in items]) for label,(title,items) in MENUS.items()}
    pack=dict(name='BMSTEPS',title='Read the steps. Fill in my numbers.',
              methods=36,steps=sum(len(g['steps']) for g in GUIDES),pages=len(pages),
              bytes=len(program.data),sha256=hashlib.sha256((OUT/'BMSTEPS.8xp').read_bytes()).hexdigest(),
              compatibility='TI-84 Plus CE / CE Python; native TI-BASIC; no helpers required',
              intro=[intro['label'],notation['label']],menus=lookup,
              guides=GUIDES,screens={p['label']:p for p in pages})
    (OUT/'manifest.json').write_text(json.dumps(pack,ensure_ascii=False,indent=2)+'\n')
    print(f'Built standalone BMSTEPS: {len(GUIDES)} methods, {pack["steps"]} steps, {len(pages)} screens, {len(program.data)} token bytes.')

if __name__=='__main__':build()
