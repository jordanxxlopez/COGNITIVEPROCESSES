"""Add collection 15 (Articles and Labs, source id 14): 12 CogLab labs and 6 assigned articles.

Reads the authored text, figure sources, video list and quiz questions from authoring/psyc301/articles-labs/
and writes psyc301-c15-data.js, which adds the collection to window.SECOND_HALF at load time. The pinned
files (module2-data.js and Versions 6 to 22) are never edited, so earlier editions stay exactly as they were.
Also writes the College-Level and Simplified wording for the shared question-versions pipeline and wires the
three HTML entry points. Safe to re-run.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'authoring/psyc301/articles-labs'
ID = 14
LECTURE = '15'
REVISION = 'articles-labs-balanced-100'


def load(name):
    return json.loads((SRC / name).read_text())


text = load('text.json')['sections']
media = load('media.json')
questions = load('questions-labs.json')['questions'] + load('questions-articles.json')['questions']
variants = load('variants-labs.json') + load('variants-articles.json')
facts = load('review-flags.json')['keyFacts']

pages = [s['page'] for s in text]
assert pages == list(range(1, len(pages) + 1)), pages
assert all(str(p) in media for p in pages), [p for p in pages if str(p) not in media]
assert len(questions) == 50, len(questions)
assert [v['id'] for v in variants] == [q['id'] for q in questions]
for q in questions:
    assert q['module'] == ID and len(q['options']) == 4 and len(set(q['options'])) == 4 and q['correct'] == 0, q['id']
    assert q['page'] in pages, q['id']

collection = dict(id=ID, title='Articles and Labs', file='PSYC301 Midterm II labs and articles',
                  sections=[dict(page=s['page'], title=s['title'], bullets=s['original'], image=i) for i, s in enumerate(text)],
                  original=[media[str(s['page'])]['imageFile'] for s in text], optional=False)
bank = dict(
    collection=collection, questions=questions, revision=REVISION, lectureNumber=LECTURE,
    topics=[dict(module=ID, title=s['title'], pages=[s['page']], progressKey='m2-topic-14-%d' % s['page']) for s in text],
    experiments=[dict(module=ID, title=s['title'], pages=[s['page']]) for s in text],
    coreReview=[dict(module=ID, title='Short-term and sensory memory labs', pages=[1, 2, 3, 4, 5, 6]),
                dict(module=ID, title='Mental imagery and reasoning labs', pages=[7, 8, 9]),
                dict(module=ID, title='Decision-making labs', pages=[10, 11, 12]),
                dict(module=ID, title='Assigned articles', pages=[13, 14, 15, 16, 17, 18])])
versions = {str(v): {str(s['page']): s['v%d' % v] for s in text} for v in (20, 21, 22)}
# Rewritten, stand-alone editions (keys r20, r21, r22): each study explained on its own, no other researchers.
rewrite = load('text-rewrite.json')
for key in ('r20', 'r21', 'r22'):
    versions[key] = {str(s['page']): rewrite[str(s['page'])][key] for s in text}
mediasec = {str(s['page']): dict(credit=media[str(s['page'])]['credit'], description=media[str(s['page'])]['description'],
                                 doi=media[str(s['page'])].get('doi', ''), source=media[str(s['page'])].get('source', ''),
                                 videos=media[str(s['page'])].get('videos', []), kind=media[str(s['page'])].get('kind', 'article')) for s in text}

MERGE = """(()=>{const b=window.SECOND_HALF,c=window.C15_BANK;if(!b||!c)return;const id=c.collection.id;
 b.collections=b.collections.filter(x=>x.id!==id).concat([c.collection]);
 b.questions=b.questions.filter(q=>q.module!==id).concat(c.questions);
 b.modules=b.modules.filter(m=>m!==id).concat([id]);
 b.lectureNumbers[id]=c.lectureNumber;b.revision=c.revision;
 for(const key of ['topics','coreReview','experiments'])b[key]=b[key].filter(g=>g.module!==id).concat(c[key]);})();
"""
out = ('// Generated by authoring/psyc301/build_articles_labs.py. Adds collection 15 to window.SECOND_HALF; module2-data.js is unchanged.\n'
       'window.C15_BANK = ' + json.dumps(bank, ensure_ascii=False) + ';\n'
       'window.C15_TEXT = ' + json.dumps(versions, ensure_ascii=False) + ';\n'
       'window.C15_MEDIA = ' + json.dumps(dict(sections=mediasec), ensure_ascii=False) + ';\n' + MERGE)
(ROOT / 'psyc301-c15-data.js').write_text(out)

# ---- College-Level and Simplified wording, through the shared question-versions pipeline
(ROOT / 'authoring/psyc301/question-versions/source/new-m14.json').write_text(json.dumps(variants, ensure_ascii=False, indent=1) + '\n')
blocks = []
for s in text:
    flat = ' '.join(b['text'] + ' ' + ' '.join(b['children']) for b in s['v22']).replace('**', '')
    blocks.append('=== %d:%d\n%s\n' % (ID, s['page'], s['title'] + '. ' + flat))
blocks.append('=== %d:99\n%s\n' % (ID, ' '.join(' '.join(v) for v in facts.values())))
(ROOT / 'authoring/psyc301/question-versions/lecture-text/m14.txt').write_text('\n'.join(blocks))

# ---- HTML entry points: data right after module2-data.js, interface last
for name in ['index.html', 'psyc301-module2.html', 'share.html']:
    html = (ROOT / name).read_text()
    if 'psyc301-c15-data.js' not in html:
        anchor = '<script src="short-term-memory-v2.js'
        assert anchor in html, (name, anchor)
        html = html.replace(anchor, '<script src="psyc301-c15-data.js?v=c15-1"></script>' + anchor, 1)
        end = '<link rel="stylesheet" href="psyc301-videos/videos.css'
        assert end in html, (name, end)
        html = html.replace(end, '<script src="psyc301-c15.js?v=c15-1"></script>' + end, 1)
    html = html.replace('module2-question-versions-data.js?v=1', 'module2-question-versions-data.js?v=c15-1')
    (ROOT / name).write_text(html)

r = subprocess.run([sys.executable, str(ROOT / 'authoring/psyc301/question-versions/build.py')], capture_output=True, text=True)
print('Added collection 15:', len(text), 'sections,', len(questions), 'questions')
print(r.stdout[-300:], r.stderr[-800:])
sys.exit(r.returncode)
