"""Build psyc301-contrasts-v2-data.js: the rewritten Side-by-side contrasts with a study-priority score per pair.

Likelihood model (heuristic, not a validated exam prediction): each pair carries `keys`. A Q&A-bank item matches when at
least two keys (or the only key) appear in its question plus answer text. The pair's score is the best matching item's
priority score plus 0.3 per extra matching item (capped at +1.5), so topics that many high-priority questions touch rank
higher. Lecture 15 studies are not in the Q&A bank, so they use a stated manual score. Tiers: >= 9 Know first,
>= 7 Know next, otherwise Know last."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'authoring/psyc301/exam-aids'))
from contrasts_v2_content_a import A
from contrasts_v2_content_b import B
from contrasts_v2_content_c import C15
from contrasts_v2_patch import PATCH, DELETE, NEW

def norm(t): return t.replace('\u2212', '-').replace('\u2013', '-')
def scrub(o):
    if isinstance(o, str): return o.replace('\u2013', '-')
    if isinstance(o, list): return [scrub(x) for x in o]
    if isinstance(o, dict): return {k: scrub(v) for k, v in o.items()}
    return o
base = A + B + C15
byt = {norm(c['title']): c for c in base}
for t in DELETE: assert norm(t) in byt, t
for t, f in PATCH.items():
    assert norm(t) in byt, t
    byt[norm(t)].update(f)
base = [c for c in base if norm(c['title']) not in {norm(t) for t in DELETE}] + NEW
base = [scrub(c) for c in base]

def load(f):
    s = (ROOT / f).read_text()
    return json.loads(s[s.index('=') + 1:].strip().rstrip(';'))

qa = load('psyc301-qa-bank-data.js')
texts = [((x['q'] + ' ' + x['a']).lower(), x['score'], x['module']) for x in qa]
out, unmatched = [], []
for c in base:
    keys = [k.lower() for k in c['keys']]
    need = 1 if len(keys) == 1 else 2
    hits = sorted([s for t, s, m in texts if sum(k in t for k in keys) >= need], reverse=True)
    if c['score'] is not None:
        score, basis = c['score'], c['basis']
    elif hits:
        score = hits[0] + min(1.5, 0.3 * (len(hits) - 1))
        basis = '%d matching Q&A question%s, best %.1f' % (len(hits), '' if len(hits) == 1 else 's', hits[0])
    else:
        score, basis = 3.0, 'no matching Q&A question'
        unmatched.append(c['title'])
    tier = 'high' if score >= 9 else 'mid' if score >= 7 else 'low'
    d = {k: c[k] for k in ('module', 'title', 'a', 'b', 'diff', 'example', 'watch')}
    d.update(score=round(score, 1), tier=tier, basis=basis)
    out.append(d)
print(len(out), 'contrasts; unmatched:', unmatched)
from collections import Counter
print(Counter(d['tier'] for d in out), Counter(d['module'] for d in out))
(ROOT / 'psyc301-contrasts-v2-data.js').write_text(
    '// Generated by authoring/psyc301/build_contrasts_v2.py\nwindow.CONTRASTS_V2 = ' + json.dumps(out, ensure_ascii=False) + ';\n')
