  "**Emotions take part in decision making** rather than only getting in its way. People with damage to an area of the prefrontal cortex, who have flattened emotions, have impaired decision making. Flattened emotions are weakened, so the person feels much less than usual, and when emotion is reduced in this way decisions get worse."
