  "**Conditional syllogism 1 is modus ponens**: *If I study, I’ll get a good grade; I studied; therefore I’ll get a good grade.* Since the condition is met, what follows from it has to follow too. The form is valid, and **97 percent of participants judged it correctly**, making it the easiest of the four to evaluate."
