  "**Conditional syllogism 2 is modus tollens**: *If I study, I’ll get a good grade; I didn’t get a good grade; therefore I didn’t study.* If studying always leads to a good grade, then missing the grade means the studying did not happen. It is just as valid as modus ponens, yet **only 60 percent of participants judged it correctly**."
