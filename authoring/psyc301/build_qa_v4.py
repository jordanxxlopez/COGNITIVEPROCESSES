"""Build psyc301-qa-v4-data.js: in-depth answers for the Version 3 questions, in the Version 20 teaching style.
Each answer is a list of main points ("- " lines are sub-points). Questions come from psyc301-qa-v3-data.js, so Version 4 keeps them exactly."""
import importlib.util, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'authoring/psyc301/qa-v4'))
import patches
raw = (ROOT / 'psyc301-qa-v3-data.js').read_text()
v3 = json.loads(raw[raw.index('['):raw.rindex(']')+1])
out = []
for m in (6, 9, 10, 11, 12, 13, 14):
    spec = importlib.util.spec_from_file_location(f'a{m}', ROOT / f'authoring/psyc301/qa-v4/m{m}.py')
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    items = [x for x in v3 if x['module'] == m]
    mod.A = patches.apply(m, mod.A)
    assert len(items) == len(mod.A), (m, len(items), len(mod.A))
    for it, ans in zip(items, mod.A):
        assert ans and not ans[0].startswith('- '), (m, it['q'])
        text = ' '.join(ans).lower()
        for bad in ('need not', 'coworker', 'lecture'):
            assert bad not in text, (bad, it['q'])
        assert ans[0].count('**') % 2 == 0 and all(a.count('**') % 2 == 0 for a in ans), (m, it['q'])
        out.append({'id': it['id'], 'a': ans})
words = sum(len(' '.join(o['a']).split()) for o in out)
(ROOT / 'psyc301-qa-v4-data.js').write_text(
    '// Generated by authoring/psyc301/build_qa_v4.py from authoring/psyc301/qa-v4/*.py\n'
    'window.QA_V4 = ' + json.dumps(out, ensure_ascii=False) + ';\n')
tags = '<script src="psyc301-qa-v4-data.js?v=v4-2"></script>'
for name in ['index.html', 'psyc301-module2.html', 'share.html']:
    p = ROOT / name
    html = p.read_text()
    if 'psyc301-qa-v4-data.js' in html:
        continue
    anchor = '<script src="psyc301-qa-v3-data.js?v=v3-2"></script>'
    assert anchor in html, name
    p.write_text(html.replace(anchor, anchor + tags, 1))
print(len(out), 'answers,', words // len(out), 'words average')
