"""Build psyc301-exam-aids-data.js from the four authored groups and wire the script into the three entry pages."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'authoring/psyc301/exam-aids'
out = {'cards': [], 'contrasts': [], 'ask': [], 'explainers': [], 'notes': []}
for g in 'ABCD':
    d = json.loads((SRC / (g + '.json')).read_text())
    ap = SRC / (g + '-answers.json')
    if ap.exists():
        ans = {a['topic']: a['answers'] for a in json.loads(ap.read_text())['answers']}
        for t in d.get('ask', []):
            a = ans.get(t['topic'])
            if a:
                assert len(a) == len(t['questions']), t['topic']
                t['answers'] = a
    ep = SRC / (g + '-explain.json')
    if ep.exists():
        ex = {a['title']: a['paragraphs'] for a in json.loads(ep.read_text())['explain']}
        for t in d.get('explainers', []):
            if t['title'] in ex:
                t['explain'] = ex[t['title']]
    np_ = SRC / (g + '-another.json')
    if np_.exists():
        an = {a['title']: a['paragraphs'] for a in json.loads(np_.read_text())['another']}
        for t in d.get('explainers', []):
            if t['title'] in an:
                t['another'] = an[t['title']]
    for k in out:
        out[k] += d.get(k, [])
(ROOT / 'psyc301-exam-aids-data.js').write_text(
    '// Generated by authoring/psyc301/build_exam_aids.py from authoring/psyc301/exam-aids/*.json\n'
    'window.EXAM_AIDS = ' + json.dumps({k: out[k] for k in ('cards', 'contrasts', 'ask', 'explainers')}, ensure_ascii=False) + ';\n')
(SRC / 'notes-for-jordan.json').write_text(json.dumps(out['notes'], ensure_ascii=False, indent=1))
tags = '<script src="psyc301-exam-aids-data.js?v=aids-1"></script><script src="psyc301-exam-aids.js?v=aids-1"></script>'
for name in ['index.html', 'psyc301-module2.html', 'share.html']:
    p = ROOT / name
    html = p.read_text()
    if 'psyc301-exam-aids.js' in html:
        continue
    anchor = '<script src="psyc301-v22.js?v=psyc301-v22-1"></script>'
    assert anchor in html, name
    p.write_text(html.replace(anchor, anchor + tags, 1))
print({k: len(v) for k, v in out.items()})
