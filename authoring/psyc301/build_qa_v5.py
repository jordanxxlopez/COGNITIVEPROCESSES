"""Build psyc301-qa-v5-data.js: Version 5 answers (professor-style) for the same 550 Version 3/4 questions.
Questions, slide references, rankings and section assignments come from psyc301-qa-v3-data.js and are not changed."""
import importlib.util, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
raw = (ROOT / 'psyc301-qa-v3-data.js').read_text()
v3 = json.loads(raw[raw.index('['):raw.rindex(']')+1])
EXPECT = {6: 87, 9: 73, 10: 73, 11: 74, 12: 92, 13: 79, 14: 72}
out = []
for m in (6, 9, 10, 11, 12, 13, 14):
    spec = importlib.util.spec_from_file_location(f'v5m{m}', ROOT / f'authoring/psyc301/qa-v5/m{m}.py')
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    items = [x for x in v3 if x['module'] == m]
    assert len(items) == EXPECT[m] == len(mod.A), (m, len(items), len(mod.A))
    for it, ans in zip(items, mod.A):
        paras = [re.sub(r'(?<!\*)\*(?!\*)', '', t) for t in ans]
        text = ' '.join(paras).lower()
        for bad in ('need not', 'coworker', 'lecture', 'the example', 'this topic'):
            assert bad not in text, (m, bad, it['q'][:60])
        for t in paras:
            assert t.count('**') % 2 == 0, (m, it['q'][:60])
        out.append({'id': it['id'], 'a': paras})
assert len(out) == 550 and len({o['id'] for o in out}) == 550
(ROOT / 'psyc301-qa-v5-data.js').write_text(
    '// Generated by authoring/psyc301/build_qa_v5.py from authoring/psyc301/qa-v5/*.py\n'
    'window.QA_V5 = ' + json.dumps(out, ensure_ascii=False) + ';\n')
words = sum(len(' '.join(o['a']).split()) for o in out)
print(len(out), 'answers,', words // len(out), 'words average')
